/* Course registry for the guided "צריך עזרה?" sections.
   Each level file (courses/<course>/<ID>.js, GENERATED by tools/build_courses.js from tools/courses_src/)
   calls CC_LEVEL("<course>", {...}); levels are kept sorted by `order`. course-ui.js renders them;
   tools/course_check.js lints them. */
window.COURSES = window.COURSES || {};
window.CC_LEVEL = function(courseId, level){
  const c = window.COURSES[courseId] || (window.COURSES[courseId] = { levels: [] });
  c.levels.push(level);
  c.levels.sort((a, b) => a.order - b.order);
};
